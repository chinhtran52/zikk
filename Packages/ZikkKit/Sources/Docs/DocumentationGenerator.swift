import Foundation
import APICore
import CodeGen
import Interop

/// Builds a single-file HTML documentation page for a collection.
public struct DocumentationGenerator {
    public var snippetLanguage: SnippetLanguage
    /// Variables used to render code snippets (URLs keep `{{variables}}` in the reference section).
    public var resolver: VariableResolver
    public var generatedAt: Date

    public init(snippetLanguage: SnippetLanguage = .curl, resolver: VariableResolver = VariableResolver(), generatedAt: Date = Date()) {
        self.snippetLanguage = snippetLanguage
        self.resolver = resolver
        self.generatedAt = generatedAt
    }

    public func html(for collection: InteropCollection) -> String {
        var nav = ""
        var body = ""
        var counter = 0

        func anchor() -> String {
            counter += 1
            return "endpoint-\(counter)"
        }

        func render(_ items: [InteropItem], inherited auth: AuthConfig, depth: Int) {
            for item in items {
                switch item {
                case .folder(let folder):
                    nav += #"<div class="folder">\#(HTML.escape(folder.name))</div>"#
                    body += "<h2>\(HTML.escape(folder.name))</h2>"
                    if !folder.description.isEmpty { body += "<div class=\"markdown\">\(MarkdownRenderer.html(folder.description))</div>" }
                    render(folder.items, inherited: folder.auth.type == .inherit ? auth : folder.auth, depth: depth + 1)
                case .request(let request):
                    let id = anchor()
                    let method = request.spec.kind == .http ? request.spec.method.rawValue : request.spec.kind.rawValue.uppercased()
                    nav += ##"<a href="#\##(id)"><span class="method \##(methodClass(method))">\##(HTML.escape(method))</span>\##(HTML.escape(request.name))</a>"##
                    body += endpoint(request, id: id, method: method, inheritedAuth: auth)
                }
            }
        }
        render(collection.items, inherited: collection.auth, depth: 0)

        var header = "<h1>\(HTML.escape(collection.name))</h1>"
        if !collection.description.isEmpty { header += "<div class=\"markdown\">\(MarkdownRenderer.html(collection.description))</div>" }
        if collection.auth.type != .none && collection.auth.type != .inherit {
            header += "<p><span class=\"badge\">Authorization: \(HTML.escape(authLabel(collection.auth)))</span></p>"
        }
        let variables = collection.variables.filter { $0.isEnabled && !$0.key.isEmpty }
        if !variables.isEmpty {
            header += "<h3>Variables</h3><table><tr><th>Name</th><th>Value</th></tr>"
            for variable in variables {
                header += "<tr><td><code>\(HTML.escape(variable.key))</code></td><td class=\"mono\">\(variable.isSecret ? "••••••" : HTML.escape(variable.value))</td></tr>"
            }
            header += "</table>"
        }
        let footer = "<p class=\"muted\" style=\"margin-top:48px\">Generated by \(HTML.escape(Branding.appName)) on \(HTML.escape(generatedAt.formatted(date: .long, time: .shortened)))</p>"

        return """
        <!doctype html>
        <html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
        <title>\(HTML.escape(collection.name)) – API Documentation</title><style>\(DocsStyle.css)</style></head>
        <body><div class="layout"><nav><h2>\(HTML.escape(collection.name))</h2>\(nav)</nav>
        <main class="content">\(header)\(body)\(footer)</main></div></body></html>
        """
    }

    private func methodClass(_ method: String) -> String {
        ["GET", "POST", "PUT", "PATCH", "DELETE"].contains(method) ? method : "OTHER"
    }

    private func authLabel(_ auth: AuthConfig) -> String {
        switch auth.type {
        case .inherit: "Inherited"
        case .none: "None"
        case .basic: "Basic Auth"
        case .bearer: "Bearer Token"
        case .apiKey: "API Key (\(auth.apiKey.key) in \(auth.apiKey.location.rawValue))"
        case .digest: "Digest Auth"
        case .oauth1: "OAuth 1.0"
        case .oauth2: "OAuth 2.0"
        case .awsSigV4: "AWS Signature"
        }
    }

    private func endpoint(_ request: InteropRequest, id: String, method: String, inheritedAuth: AuthConfig) -> String {
        let spec = request.spec
        var html = #"<section class="endpoint" id="\#(id)"><h3><span class="method \#(methodClass(method))">\#(HTML.escape(method))</span> \#(HTML.escape(request.name))</h3>"#
        html += "<div class=\"url\">\(HTML.escape(spec.url))</div>"
        if !request.description.isEmpty { html += "<div class=\"markdown\">\(MarkdownRenderer.html(request.description))</div>" }

        let auth = spec.auth.type == .inherit ? inheritedAuth : spec.auth
        if auth.type != .none && auth.type != .inherit {
            html += "<p><span class=\"badge\">Authorization: \(HTML.escape(authLabel(auth)))\(spec.auth.type == .inherit ? " (inherited)" : "")</span></p>"
        }
        html += table("Path Variables", spec.pathVariables)
        html += table("Query Params", spec.params)
        html += table("Headers", spec.headers)

        switch spec.body.mode {
        case .none: break
        case .raw:
            let text = spec.body.rawLanguage == .json ? (JSONFormatter.prettyPrinted(spec.body.raw) ?? spec.body.raw) : spec.body.raw
            html += "<h3>Body <span class=\"badge\">\(spec.body.rawLanguage.rawValue)</span></h3><pre>\(HTML.escape(text))</pre>"
        case .urlEncoded:
            html += table("Body (x-www-form-urlencoded)", spec.body.urlEncoded)
        case .formData:
            let fields = spec.body.formData.filter { !$0.key.isEmpty }
            let showsNotes = fields.contains { !$0.notes.isEmpty }
            html += "<h3>Body (form-data)</h3><table><tr><th>Key</th><th>Type</th><th>Value</th>\(showsNotes ? "<th>Notes</th>" : "")</tr>"
            for field in fields {
                html += "<tr class=\"\(field.isEnabled ? "" : "disabled")\"><td><code>\(HTML.escape(field.key))</code></td><td>\(field.kind.rawValue)</td><td class=\"mono\">\(HTML.escape(field.kind == .file ? (field.file?.fileName ?? "") : field.value))</td>"
                    + (showsNotes ? "<td>\(HTML.escape(field.notes))</td>" : "") + "</tr>"
            }
            html += "</table>"
        case .binary:
            html += "<h3>Body (binary)</h3><p class=\"mono\">\(HTML.escape(spec.body.binary?.fileName ?? ""))</p>"
        case .graphQL:
            html += "<h3>GraphQL Query</h3><pre>\(HTML.escape(spec.body.graphQL.query))</pre>"
            if !spec.body.graphQL.variables.isEmpty { html += "<h3>GraphQL Variables</h3><pre>\(HTML.escape(spec.body.graphQL.variables))</pre>" }
        }

        if spec.kind == .http, let snippet = try? SnippetRequest(spec: spec, resolver: resolver, auth: auth) {
            html += "<details><summary>Example request · \(HTML.escape(snippetLanguage.title))</summary><pre>\(HTML.escape(CodeGenerator.generate(snippet, language: snippetLanguage)))</pre></details>"
        }

        for example in request.examples {
            let status = example.response.statusCode
            html += "<details><summary>Example response: \(HTML.escape(example.name)) <span class=\"status s\(status / 100)\">\(status)</span></summary>"
            if !example.response.headers.isEmpty {
                html += "<table>" + example.response.headers.map { "<tr><td><code>\(HTML.escape($0.key))</code></td><td class=\"mono\">\(HTML.escape($0.value))</td></tr>" }.joined() + "</table>"
            }
            if let text = example.response.bodyText, !text.isEmpty {
                html += "<pre>\(HTML.escape(JSONFormatter.prettyPrinted(text) ?? text))</pre>"
            }
            html += "</details>"
        }
        return html + "</section>"
    }

    private func table(_ title: String, _ rows: [KeyValue]) -> String {
        let rows = rows.filter { !$0.key.isEmpty }
        guard !rows.isEmpty else { return "" }
        var html = "<h3>\(HTML.escape(title))</h3><table><tr><th>Key</th><th>Value</th><th>Description</th></tr>"
        for row in rows {
            html += "<tr class=\"\(row.isEnabled ? "" : "disabled")\"><td><code>\(HTML.escape(row.key))</code></td><td class=\"mono\">\(HTML.escape(row.value))</td><td>\(HTML.escape(row.description))</td></tr>"
        }
        return html + "</table>"
    }
}
